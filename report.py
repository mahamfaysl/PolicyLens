"""Export an AuditReport as Markdown or JSON."""
import re

from schema import AuditReport

VERIFICATION_LABELS = {
    "verified": "Verified",
    "page_corrected": "Verified (page corrected)",
    "partial": "Partial match",
    "unverified": "Not found in source",
    "no_quote": "No quote given",
}


def safe_filename(name: str, fallback: str = "report") -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return slug or fallback


def to_json(report: AuditReport) -> str:
    return report.model_dump_json(indent=2)


def _cell(text) -> str:
    return str(text if text is not None else "—").replace("|", "\\|").replace("\n", " ")


def to_markdown(report: AuditReport) -> str:
    s, m = report.synthesis, report.meta
    lines = [
        f"# PolicyLens Dossier: {s.institution_name}",
        f"**Project:** {s.project_title}  ",
        f"**Sector:** {s.sector}  ",
        f"**Source:** {m.filename or 'uploaded PDF'} ({m.pages} pages)",
        "",
        "## Executive Summary",
        s.executive_summary,
        "",
        "## Core Objectives",
        *[f"- {o}" for o in s.core_objectives],
        "",
        f"## Indicator Verification Matrix ({report.verified_count}/{len(report.indicators)} quotes verified)",
        "| Indicator | Baseline | Target | Status / gap | Page | Evidence check |",
        "|---|---|---|---|---|---|",
    ]
    for i in report.indicators:
        lines.append(
            f"| {_cell(i.indicator_name)} | {_cell(i.baseline_value)} | {_cell(i.target_value)} | "
            f"{_cell(i.status_or_evidence_gap)} | {_cell(i.source_page)} | {VERIFICATION_LABELS[i.verification]} |"
        )
    lines += [
        "",
        "## Key Bottlenecks",
        *[f"- {b}" for b in s.implementation_bottlenecks],
        "",
        "## Strategic Briefing Angle",
        s.stakeholder_briefing_angle,
        "",
        "## Outreach Memo",
        s.tailored_outreach_memo,
        "",
        "---",
        f"_Generated by PolicyLens with {m.model} in {m.elapsed_s}s ({m.mode.replace('_', '-')}, {m.chunks} section(s)). "
        "AI-generated: check figures against the source before relying on them._",
    ]
    if m.warnings:
        lines += ["", "**Warnings:**", *[f"- {w}" for w in m.warnings]]
    return "\n".join(lines) + "\n"
